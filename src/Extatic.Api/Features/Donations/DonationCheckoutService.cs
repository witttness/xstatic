using Extatic.Api.Data;
using Extatic.Api.Features.Donations.Providers;
using Extatic.Api.Services;
using Microsoft.EntityFrameworkCore;

namespace Extatic.Api.Features.Donations;

public class DonationCheckoutService(
    AppDbContext db,
    DonationCampaignService campaigns,
    PaymentProviderConfigService configs,
    PaymentProviderRegistry registry,
    ILogger<DonationCheckoutService> logger)
{
    public const int MaxMessageLength = 500;
    public const int MaxDonorNameLength = 100;

    /// <summary>
    /// Creates a Pending donation, opens a hosted checkout with the tenant's provider and returns its URL.
    /// Provider failures mark the donation Failed and surface as <see cref="PaymentProviderException"/>.
    /// </summary>
    public async Task<CheckoutResponse> CheckoutAsync(Guid appId, Guid? appUserId, string ipHash,
        ClientCheckoutRequest req, CancellationToken ct = default)
    {
        var now = DateTime.UtcNow;
        var campaign = string.IsNullOrWhiteSpace(req.CampaignSlug)
            ? await campaigns.GetDefaultOpenAsync(appId, now)
            : await campaigns.GetOpenBySlugAsync(appId, req.CampaignSlug.Trim(), now);

        var interval = DonationApiValues.ParseInterval(req.Interval);
        var errors = new List<ValidationError>();
        if (req.Currency is not null && !string.Equals(req.Currency.Trim(), campaign.Currency, StringComparison.OrdinalIgnoreCase))
            errors.Add(new("currency", $"This campaign accepts {campaign.Currency} only"));
        if (interval != DonationInterval.OneTime && !campaign.AllowRecurring)
            errors.Add(new("interval", "This campaign does not accept recurring donations"));
        ValidateAmount(campaign, req.AmountMinor, errors);

        var donorName = Clean(req.DonorName, singleLine: true);
        if (donorName?.Length > MaxDonorNameLength) errors.Add(new("donor_name", $"At most {MaxDonorNameLength} characters"));
        var message = Clean(req.Message, singleLine: false);
        if (message?.Length > MaxMessageLength) errors.Add(new("message", $"At most {MaxMessageLength} characters"));
        var donorEmail = string.IsNullOrWhiteSpace(req.DonorEmail) ? null : req.DonorEmail.Trim();
        if (donorEmail is not null && !DonationCampaignService.IsEmail(donorEmail))
            errors.Add(new("donor_email", "Invalid email address"));
        if (errors.Count > 0) throw new ValidationException("Invalid donation", errors);

        if (donorEmail is null && appUserId is not null)
        {
            var userEmail = await db.AppUsers.Where(u => u.AppId == appId && u.Id == appUserId)
                .Select(u => u.Email).SingleOrDefaultAsync(ct);
            if (DonationCampaignService.IsEmail(userEmail)) donorEmail = userEmail;
        }

        var config = await configs.GetCheckoutConfigAsync(appId)
            ?? throw new ConflictException("Donations are not available for this app yet");
        var provider = registry.Get(config.Provider);

        var donation = new Donation
        {
            AppId = appId,
            CampaignId = campaign.Id,
            AppUserId = appUserId,
            AmountMinor = req.AmountMinor,
            Currency = campaign.Currency,
            Interval = interval,
            Status = DonationStatus.Pending,
            DonorName = donorName,
            DonorEmail = donorEmail,
            IsAnonymous = req.IsAnonymous ?? false,
            Message = message,
            Provider = provider.Name,
            IpHash = ipHash
        };
        db.Donations.Add(donation);
        await db.SaveChangesAsync(ct); // Id is generated by the database

        try
        {
            var credentials = configs.Credentials(config);
            var session = await provider.CreateCheckoutAsync(credentials, new CheckoutRequest(
                donation.Id, appId, donation.AmountMinor, donation.Currency, interval, campaign.Name,
                RedirectUrls.WithDonationId(campaign.SuccessUrl, donation.Id), campaign.CancelUrl,
                donation.DonorEmail), ct);
            donation.ProviderSessionId = session.SessionId;
            await db.SaveChangesAsync(CancellationToken.None);
            return new CheckoutResponse(donation.Id, session.CheckoutUrl);
        }
        catch (PaymentProviderException)
        {
            logger.LogWarning("Checkout for donation {DonationId} failed at provider {Provider}", donation.Id, provider.Name);
            donation.Status = DonationStatus.Failed;
            await db.SaveChangesAsync(CancellationToken.None);
            throw;
        }
    }

    public static void ValidateAmount(DonationCampaign campaign, long amountMinor, List<ValidationError> errors)
    {
        if (amountMinor < 1)
            errors.Add(new("amount_minor", "Must be a positive integer amount in minor units"));
        else if (amountMinor < campaign.MinAmountMinor)
            errors.Add(new("amount_minor", $"Minimum is {Currencies.Display(campaign.MinAmountMinor, campaign.Currency)}"));
        else if (amountMinor > campaign.MaxAmountMinor)
            errors.Add(new("amount_minor", $"Maximum is {Currencies.Display(campaign.MaxAmountMinor, campaign.Currency)}"));
        else if (!campaign.AllowCustomAmount && !campaign.SuggestedAmountsMinor.Contains(amountMinor))
            errors.Add(new("amount_minor", "Choose one of the suggested amounts"));
    }

    public async Task<DonationStatusDto> GetStatusAsync(Guid appId, Guid donationId)
    {
        var status = await db.Donations.Where(d => d.AppId == appId && d.Id == donationId)
            .Select(d => (DonationStatus?)d.Status).SingleOrDefaultAsync()
            ?? throw new NotFoundException("Donation not found");
        return new DonationStatusDto(status.ToApi());
    }

    /// <summary>Trims, strips control characters (keeps newlines in multi-line text). Empty → null.</summary>
    internal static string? Clean(string? value, bool singleLine)
    {
        if (value is null) return null;
        var chars = value.Where(ch => !char.IsControl(ch) || (!singleLine && ch == '\n')).ToArray();
        var cleaned = new string(chars).Trim();
        return cleaned.Length == 0 ? null : cleaned;
    }
}
